const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { resolve } = require('node:path');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.AUDIT_BROWSER ? { executablePath: process.env.AUDIT_BROWSER } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://localhost:4317');
    await page.locator('#commission-main-ledger .audit-template-controls').waitFor();
    const main = page.locator('#commission-main-ledger');
    const mainTemplates = page.locator('#auditHeaderTemplateSlot');
    await main.scrollIntoViewIfNeeded();
    const statusNav = page.locator('.commission-status-navigators');
    await statusNav.waitFor();
    assert.equal(await statusNav.locator('.commission-status-navigator').count(), 2);
    const pendingStatus = statusNav.locator('[data-commission-table-status="arrival_status"][data-commission-table-status-value="pending"]');
    await pendingStatus.click();
    assert.equal(await pendingStatus.getAttribute('aria-pressed'), 'true');
    const allArrivals = statusNav.locator('[data-commission-table-status="arrival_status"][data-commission-table-status-value=""]');
    await allArrivals.click();
    assert.equal(await allArrivals.getAttribute('aria-pressed'), 'true');
    const firstOrderStatus = statusNav.locator('[data-commission-table-status="order_status"]:not([data-commission-table-status-value=""])').first();
    if (await firstOrderStatus.count()) { await firstOrderStatus.click(); assert.equal(await firstOrderStatus.getAttribute('aria-pressed'), 'true'); }
    await statusNav.screenshot({ path: resolve(__dirname, '../commission-status-navigators.png') });
    for (const name of ['Pending Payments', 'Insurance Cases', 'Battery Tester', 'Monthly Review', 'Audit Exceptions']) {
      await mainTemplates.locator('.audit-template-menu summary').click();
      await mainTemplates.locator('[data-audit-action="add"]').click();
      await page.locator('#audit-template-dialog input[name="name"]').fill(name);
      await page.locator('#audit-template-dialog button[type="submit"]').click();
    }
    let saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ledger-finance-audit-views-v1')));
    assert.equal(saved.tables['commission-main:table'].slots[0].name, 'Pending Payments');
    assert.equal(saved.tables['commission-main:table'].slots.length, 5);
    await mainTemplates.locator('.audit-template-menu summary').click();
    assert.equal(await mainTemplates.locator('.audit-template-slot').count(), 5);
    assert.equal(await mainTemplates.locator('[data-audit-action="add"]').count(), 1);
    await mainTemplates.locator('.audit-template-popover').screenshot({ path: resolve(__dirname, '../template-filter-dynamic.png') });
    await mainTemplates.locator('.audit-template-menu summary').click();
    await page.locator('.app-rail').screenshot({ path: resolve(__dirname, '../template-filter-header.png') });
    await main.locator('[data-duplicate-table]').click();
    const copy = page.locator('.table-copy[data-audit-table]').first();
    await copy.waitFor();
    const copyId = await copy.getAttribute('data-audit-table');
    await copy.locator('.audit-template-menu summary').click();
    assert.equal(await copy.locator('.audit-template-slot').count(), 0);
    assert.equal(await copy.locator('[data-audit-action="add"]').count(), 1);
    await copy.locator('[data-audit-action="add"]').click();
    await page.locator('#audit-template-dialog input[name="name"]').fill('Copy private view');
    await page.locator('#audit-template-dialog button[type="submit"]').click();
    const copyBefore = await copy.locator('tbody').innerText();
    await main.locator('[data-search]').fill('no-such-rider-qa');
    await main.locator('[data-search]').press('Enter');
    assert.match(await mainTemplates.locator('.audit-template-menu summary').getAttribute('title'), /Modified/);
    assert.equal(await copy.locator('tbody').innerText(), copyBefore);
    await mainTemplates.locator('.audit-template-menu summary').click();
    await mainTemplates.locator('[data-audit-action="apply"][data-audit-slot="0"]').click();
    assert.equal(await main.locator('[data-search]').inputValue(), '');
    await mainTemplates.locator('.audit-template-menu summary').click();
    await mainTemplates.locator('[data-audit-action="rename"][data-audit-slot="0"]').click();
    await page.locator('#audit-template-dialog input[name="name"]').fill('My arrival filter');
    await page.locator('#audit-template-dialog button[type="submit"]').click();
    await main.locator('[data-search]').fill('saved-last-search');
    await main.locator('[data-search]').press('Enter');
    await page.reload();
    await main.locator('.audit-template-controls').waitFor();
    assert.equal(await main.locator('[data-search]').inputValue(), 'saved-last-search');
    saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ledger-finance-audit-views-v1')));
    assert.equal(saved.tables[copyId].slots[0].name, 'Copy private view');
    assert.equal(saved.tables['commission-main:table'].slots[0].name, 'My arrival filter');
    await mainTemplates.locator('.audit-template-menu summary').click();
    await mainTemplates.locator('[data-audit-action="update"][data-audit-slot="0"]').click();
    assert.match(await page.locator('#audit-template-dialog').innerText(), /Overwrite saved filters/);
    await page.locator('#audit-template-dialog button[type="submit"]').click();
    await mainTemplates.locator('.audit-template-menu summary').click();
    await mainTemplates.locator('[data-audit-action="clear"][data-audit-slot="1"]').click();
    await page.locator('#audit-template-dialog button[type="submit"]').click();
    saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ledger-finance-audit-views-v1')));
    assert.equal(saved.tables['commission-main:table'].slots.length, 4);
    await main.locator('[data-audit-date]').click();
    while ((await page.locator('#audit-template-dialog .audit-calendar-head strong').innerText()) !== 'August 2026') await page.locator('#audit-template-dialog [data-audit-calendar-month="1"]').click();
    await page.locator('#audit-template-dialog [data-audit-calendar-date="2026-08-01"]').click();
    await page.locator('#audit-template-dialog [data-audit-calendar-date="2026-08-07"]').click();
    await page.locator('#audit-template-dialog').screenshot({ path: resolve(__dirname, '../audit-calendar-desktop.png') });
    await page.locator('#audit-template-dialog button[type="submit"]').click();
    saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ledger-finance-audit-views-v1')));
    assert.equal(saved.tables['commission-main:table'].last.scope.dates.start, '2026-08-01 00:00:00');
    assert.notEqual(saved.tables[copyId].last.scope.dates.start, '2026-08-01 00:00:00');
    await main.locator('.audit-quick-menu summary').click();
    await main.locator('[data-audit-quick="last-week"]').click();
    saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ledger-finance-audit-views-v1')));
    const quickDates = saved.tables['commission-main:table'].last.scope.dates;
    assert.equal(new Date(quickDates.start.replace(' ', 'T') + 'Z').getUTCDay(), 1);
    assert.equal(new Date(quickDates.end.replace(' ', 'T') + 'Z').getUTCDay(), 0);
    assert.notDeepEqual(saved.tables[copyId].last.scope.dates, quickDates);
    await main.screenshot({ path: resolve(__dirname, '../audit-templates-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await main.scrollIntoViewIfNeeded();
    await main.locator('.audit-quick-menu summary').click();
    await main.locator('.audit-quick-popover:popover-open').waitFor();
    const box = await main.locator('.audit-quick-popover').boundingBox();
    await page.screenshot({ path: resolve(__dirname, '../audit-templates-phone.png') });
    assert.ok(box.x >= 0 && box.x + box.width <= 391);
    assert.deepEqual(errors, []);
    console.log('PASS: templates, independent quick dates, custom dates, refresh persistence, desktop and phone layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
